import app.niko.*

var ok = 0
var total = 0
fun t(name: String, cond: Boolean) { total++; if (cond) ok++; println((if (cond) "✅ " else "❌ ") + name) }
fun p(s: String) = CmdParser.parse(s)

fun main() {
    t("fold İ/I/ş", CmdParser.fold("İSTANBUL ILIK ŞEKER") == "istanbul ilik seker")
    t("normPhone", CmdParser.normPhone("0532 123 45 67") == "905321234567" && CmdParser.normPhone("+90 505 111 22 33") == "905051112233" && CmdParser.normPhone("123") == "")
    t("nameScore anneyi/annemi", CmdParser.nameScore("anneyi", "Anne") > 0 && CmdParser.nameScore("annemi", "Anne") > 0 && CmdParser.nameScore("annemi", "Annem") > 0)
    t("nameScore ilk ad: aliyi → Ali Veli", CmdParser.nameScore("aliyi", "Ali Veli") == 3)
    t("nameScore en uzun kazanır", CmdParser.nameScore("alihanı", "Alihan") > CmdParser.nameScore("alihanı", "Ali"))
    t("nameScore eşleşmeyen", CmdParser.nameScore("mehmeti", "Ahmet") == 0)
    t("Cancel/EndCall", p("iptal") == Cmd.Cancel && p("Dur") == Cmd.Cancel && p("görüşürüz") == Cmd.EndCall && p("kapat") == Cmd.EndCall)
    t("Sos", p("imdat") == Cmd.Sos && p("acil durum") == Cmd.Sos && p("tehlikedeyim") == Cmd.Sos)
    t("Help/Battery/Time/Date", p("ne yapabilirsin") == Cmd.Help && p("pil kaç") == Cmd.Battery && p("şarj yüzde kaç") == Cmd.Battery && p("saat kaç") == Cmd.TimeNow && p("bugün günlerden ne") == Cmd.DateNow)
    t("Call anneyi ara", p("anneyi ara") == Cmd.Call("anneyi", null))
    t("Call Ahmet'i arar mısın", p("Ahmet'i arar mısın?") == Cmd.Call("Ahmet'i", null))
    t("Call 112", p("112'yi ara") == Cmd.Call("112", "112"))
    t("Call numara", p("0532 123 45 67'yi ara") == Cmd.Call("0532 123 45 67'yi", "+905321234567"))
    t("uzun cümle arama sanılmaz", p("bana bir tarif öner ve açıkla lütfen şimdi ara") is Cmd.Chat)
    t("beni ara (süresiz) → Reply", p("beni ara") is Cmd.Reply)
    t("Niko'yu ara → Reply", p("Niko'yu ara") is Cmd.Reply)
    var c = p("10 dakika sonra beni ara toplantı var"); t("Timer 10 dk: toplantı var", c is Cmd.Timer && c.seconds == 600 && c.label == "toplantı var")
    c = p("on dakika sonra hatırlat"); t("Timer 'on dakika' (kelime)", c is Cmd.Timer && c.seconds == 600)
    c = p("1 saat 30 dakika zamanlayıcı kur"); t("Timer 1s30dk", c is Cmd.Timer && c.seconds == 5400)
    c = p("yarım saat sonra hatırlat makarna"); t("Timer yarım saat", c is Cmd.Timer && c.seconds == 1800 && c.label == "makarna")
    c = p("bir buçuk saat sonra uyar"); t("Timer bir buçuk saat", c is Cmd.Timer && c.seconds == 5400)
    c = p("30 saniye zamanlayıcı"); t("Timer 30 sn", c is Cmd.Timer && c.seconds == 30)
    c = p("zamanlayıcı kur"); t("Timer süre yok → -1", c is Cmd.Timer && c.seconds < 0)
    c = p("yarın sabah 7'ye alarm kur"); t("Alarm 07:00", c is Cmd.Alarm && c.hour == 7 && c.minute == 0)
    c = p("akşam 7'ye alarm kur"); t("Alarm akşam 7 → 19:00", c is Cmd.Alarm && c.hour == 19)
    c = p("alarm kur 6:30"); t("Alarm 6:30", c is Cmd.Alarm && c.hour == 6 && c.minute == 30)
    c = p("yedi buçuğa alarm kur"); t("Alarm yedi buçuk (kelime)", c is Cmd.Alarm && c.hour == 7 && c.minute == 30)
    c = p("saat 14.45 için alarm"); t("Alarm 14.45", c is Cmd.Alarm && c.hour == 14 && c.minute == 45)
    c = p("alarm kur"); t("Alarm saat yok → -1", c is Cmd.Alarm && c.hour < 0)
    c = p("5 dakika sonraya alarm kur"); t("'5 dk sonra alarm' → Timer", c is Cmd.Timer && c.seconds == 300)
    t("alarmı iptal et → Reply", p("alarmı iptal et") is Cmd.Reply)
    c = p("anneye mesaj at geliyorum"); t("SMS anneye", c is Cmd.Sms && !c.whatsapp && c.body == "geliyorum" && c.name == "anneye")
    c = p("Ahmet'e whatsapp yaz Selam, nasılsın?"); t("WhatsApp gövde korunur", c is Cmd.Sms && c.whatsapp && c.body == "Selam, nasılsın?")
    c = p("whatsapp'tan anneme yaz akşam geliyorum"); t("WhatsApp ön ek", c is Cmd.Sms && c.whatsapp && c.name == "anneme" && c.body == "akşam geliyorum")
    c = p("05321234567 sms gönder merhaba"); t("SMS numaraya", c is Cmd.Sms && c.number == "+905321234567" && c.body == "merhaba")
    c = p("anneme mesaj at"); t("SMS gövde boş", c is Cmd.Sms && c.body == "")
    c = p("konumumu anneme gönder"); t("Konum anneme", c is Cmd.SendLocation && c.name == "anneme")
    c = p("konumumu gönder"); t("Konum (acil kişi)", c is Cmd.SendLocation && c.name == "")
    t("el fenerini aç/kapat", p("el fenerini aç") == Cmd.Flashlight(true) && p("fener kapat") == Cmd.Flashlight(false))
    t("ses", p("sesi aç") == Cmd.Volume(1) && p("sesi biraz kıs") == Cmd.Volume(-1) && p("sessize al") == Cmd.Volume(0))
    c = p("youtube'u aç"); t("OpenApp youtube'u aç", c is Cmd.OpenApp && c.name == "youtube")
    c = p("kamerayı aç"); t("OpenApp kamerayı aç", c is Cmd.OpenApp && c.name == "kamera")
    c = p("WhatsApp'ı aç"); t("OpenApp WhatsApp'ı aç", c is Cmd.OpenApp && c.name == "WhatsApp")
    t("ayarlar", p("ayarları aç") == Cmd.OpenSettings("settings") && p("bluetooth ayarlarını aç") == Cmd.OpenSettings("bluetooth") && p("wifi ayarlarını aç") == Cmd.OpenSettings("wifi"))
    c = p("youtube'da tarkan şımarık aç"); t("YouTube sorgusu", c is Cmd.YouTube && c.query == "tarkan şımarık")
    c = p("Sezen Aksu çal"); t("'X çal' → YouTube", c is Cmd.YouTube && c.query == "Sezen Aksu")
    c = p("google'da ara hava durumu ankara"); t("Search", c is Cmd.Search && c.query == "hava durumu ankara")
    c = p("Kadıköy'e git"); t("Navigate Kadıköy'e git", c is Cmd.Navigate && c.query == "Kadıköy" && !c.nearby)
    c = p("Antalya'ya yol tarifi"); t("Navigate yol tarifi", c is Cmd.Navigate && c.query.startsWith("Antalya"))
    c = p("yakınımda eczane"); t("Yakında eczane", c is Cmd.Navigate && c.query == "eczane" && c.nearby)
    t("normal sohbet → Chat", p("merhaba nasılsın") is Cmd.Chat && p("türkiye'nin başkenti neresi") is Cmd.Chat)
    t("boş girdi çökmez", p("") is Cmd.Chat && p("   ") is Cmd.Chat && p("?") is Cmd.Chat)
    t("Wake: Niko anneyi ara", Wake.extract("Niko anneyi ara") == (true to "anneyi ara"))
    t("Wake: hey Niko saat kaç", Wake.extract("hey Niko saat kaç") == (true to "saat kaç"))
    t("Wake: komut önde, Niko sonda", Wake.extract("anneyi ara niko") == (true to "anneyi ara"))
    t("Wake: sadece Niko", Wake.extract("Niko") == (true to ""))
    t("Wake: Niko'ya saat kaç", Wake.extract("Niko'ya saat kaç") == (true to "saat kaç"))
    t("Wake: televizyon konuşması tetiklemez", Wake.extract("televizyonda haber var") == (false to "televizyonda haber var"))
    t("Wake: Nikolas ≠ Niko", !Wake.extract("Nikolas geldi").first)
    t("StopListening", p("dinlemeyi bırak") == Cmd.StopListening && p("Niko uyu") == Cmd.StopListening)
    println("\nSONUÇ: $ok/$total")
    if (ok != total) System.exit(1)
}
